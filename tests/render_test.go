package tests

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// renderFlow is a minimal materialized flow: one app-manifests action
// writing gen/app.yaml, driving one object so plan has something real
// to diff. No target.context — context comes from --context at the
// command line, never from the file.
const renderFlow = `apiVersion: afon.dev/flow/v1
kind: Flow
metadata:
  name: hello
spec:
  target:
    namespace: demo
  nodes:
    - id: app
      type: app-manifests
      config:
        name: hello
        image: %s
        port: 8080
        out: gen/app.yaml
    - id: obj
      type: fake-object
      config:
        kind: ConfigMap
        name: hello
        data:
          msg: ${app.rendered}
`

// writeRenderFlow drops the flow into a fresh temp dir and returns the
// flow path.
func writeRenderFlow(t *testing.T, image string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "flow.yaml")
	content := strings.Replace(renderFlow, "%s", image, 1)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func mustReadFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// TestCLIRenderLifecycle walks the whole materialized contract through
// the real binary: render writes the headered file, plan reads it as
// the artifact (file status, real downstream diff), a flow edit warns
// as stale but never changes plan's behavior, re-render clears the
// warning, apply executes with the file as truth, --show-rendered
// prints the bytes, and a deleted file fails plan naming this command.
func TestCLIRenderLifecycle(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	dir := filepath.Dir(flow)
	appPath := filepath.Join(dir, "gen", "app.yaml")

	// 1. render writes the file with the provenance header.
	r := runAf(t, nil, "render", "-f", flow)
	if r.code != 0 {
		t.Fatalf("render exit = %d\nstderr: %s", r.code, r.stderr)
	}
	wantStderrContains(t, r, "written", "gen/app.yaml")
	content := mustReadFile(t, appPath)
	if !strings.HasPrefix(content, "# Generated by afon render") {
		t.Errorf("missing provenance header:\n%.120s", content)
	}
	if !strings.Contains(content, "kind: Deployment") || !strings.Contains(content, "namespace: demo") {
		t.Errorf("rendered body wrong:\n%s", content)
	}
	if !strings.Contains(r.stdout, "kind: Deployment") {
		t.Errorf("stdout missing rendered YAML:\n%s", r.stdout)
	}

	// 2. plan reads the file: action entry is "file", downstream gets a
	// real diff (not known-after-apply), no staleness warning yet.
	r = runAf(t, nil, "plan", "-f", flow)
	if r.code != 0 {
		t.Fatalf("plan exit = %d\nstderr: %s", r.code, r.stderr)
	}
	if !strings.Contains(r.stdout, "file") {
		t.Errorf("plan missing file status:\n%s", r.stdout)
	}
	if strings.Contains(r.stderr, "stale") {
		t.Errorf("clean plan warned stale:\n%s", r.stderr)
	}

	// 3. Flow edit after render: plan warns on stderr but still plans
	// from the file (the file is the artifact — no implicit render).
	flowEdited := strings.Replace(mustReadFile(t, flow), "nginx:1.27-alpine", "nginx:1.28", 1)
	if err := os.WriteFile(flow, []byte(flowEdited), 0o644); err != nil {
		t.Fatal(err)
	}
	r = runAf(t, nil, "plan", "-f", flow)
	if r.code != 0 {
		t.Fatalf("stale plan exit = %d\nstderr: %s", r.code, r.stderr)
	}
	wantStderrContains(t, r, "warning: node \"app\"", "stale", "afon render")
	if !strings.Contains(r.stdout, "file") {
		t.Errorf("stale plan must still plan from the file:\n%s", r.stdout)
	}

	// 4. Re-render refreshes the file; the warning clears.
	r = runAf(t, nil, "render", "-f", flow)
	if r.code != 0 {
		t.Fatalf("re-render exit = %d\nstderr: %s", r.code, r.stderr)
	}
	content = mustReadFile(t, appPath)
	if !strings.Contains(content, "image: nginx:1.28") {
		t.Errorf("file not refreshed:\n%s", content)
	}
	r = runAf(t, nil, "plan", "-f", flow)
	if strings.Contains(r.stderr, "stale") {
		t.Errorf("warning did not clear after render:\n%s", r.stderr)
	}

	// 5. apply executes against the fake driver with the file as truth.
	r = runAf(t, nil, "apply", "-f", flow)
	if r.code != 0 {
		t.Fatalf("apply exit = %d\nstderr: %s", r.code, r.stderr)
	}
	wantStderrContains(t, r, "fake driver: no cluster is touched")
	if !strings.Contains(r.stdout, "succeeded") {
		t.Errorf("apply result missing succeeded:\n%s", r.stdout)
	}

	// 6. --show-rendered prints the plan's known outputs to stderr
	// before executing (stdout stays a clean plan/result stream).
	r = runAf(t, nil, "apply", "--show-rendered", "-f", flow)
	if r.code != 0 {
		t.Fatalf("apply --show-rendered exit = %d\nstderr: %s", r.code, r.stderr)
	}
	wantStderrContains(t, r, "--- node app output rendered ---", "kind: Deployment")

	// 7. Delete the file: plan fails loudly, naming the fix.
	if err := os.Remove(appPath); err != nil {
		t.Fatal(err)
	}
	r = runAf(t, nil, "plan", "-f", flow)
	wantExit(t, r, "plan", "-f", flow)
	wantStderrContains(t, r, "missing", `run "afon render" first`)
}

// TestCLIRenderFlagErrors pins the flag contracts on the real binary:
// --node with --all, --out without --node, and a flow with nothing to
// materialize under the default mode.
func TestCLIRenderFlagErrors(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")

	r := runAf(t, nil, "render", "-f", flow, "--node", "app", "--all")
	wantExit(t, r, "render", "--node", "app", "--all")
	wantStderrContains(t, r, "--node and --all are mutually exclusive")

	r = runAf(t, nil, "render", "-f", flow, "--out", "gen/adhoc.yaml")
	wantExit(t, r, "render", "--out")
	wantStderrContains(t, r, "--out requires --node")

	ephemeralFlow := filepath.Join(filepath.Dir(flow), "ephemeral.yaml")
	src := strings.Replace(mustReadFile(t, flow), "        out: gen/app.yaml\n", "", 1)
	if err := os.WriteFile(ephemeralFlow, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	r = runAf(t, nil, "render", "-f", ephemeralFlow)
	wantExit(t, r, "render", "-f", ephemeralFlow)
	wantStderrContains(t, r, "no materialized nodes in flow")
}

// TestCLIPlanNoImplicitRender: a flow whose materialized file never
// existed fails plan (and apply) with the same actionable error —
// plan/apply never render on the user's behalf.
func TestCLIPlanNoImplicitRender(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	r := runAf(t, nil, "plan", "-f", flow)
	wantExit(t, r, "plan", "-f", flow)
	wantStderrContains(t, r, "missing", `run "afon render" first`)

	r = runAf(t, nil, "apply", "-f", flow)
	wantExit(t, r, "apply", "-f", flow)
	wantStderrContains(t, r, "missing", `run "afon render" first`)
}
