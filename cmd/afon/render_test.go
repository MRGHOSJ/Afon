// resetRenderFlags restores every flag runRender reads, so tests that
// poke the package-level state cannot leak into each other.
func resetRenderFlags(t *testing.T, flow string) {
	t.Helper()
	prevFlow, prevNode := flagFlowFile, flagRenderNode
	prevAll, prevForce := flagRenderAll, flagRenderForce
	prevCheck, prevOut := flagRenderCheck, flagRenderOut
	t.Cleanup(func() {
		flagFlowFile, flagRenderNode = prevFlow, prevNode
		flagRenderAll, flagRenderForce = prevAll, prevForce
		flagRenderCheck, flagRenderOut = prevCheck, prevOut
	})
	flagFlowFile = flow
	flagRenderNode, flagRenderOut = "", ""
	flagRenderAll, flagRenderForce, flagRenderCheck = false, false, false
}

// captureStdoutStderr runs fn with os.Stdout and os.Stderr redirected
// to pipes and returns what was written (outputs are small — the pipe
// buffer cannot block).
func captureStdoutStderr(t *testing.T, fn func() error) (stdout, stderr string, err error) {
	t.Helper()
	origOut, origErr := os.Stdout, os.Stderr
	rOut, wOut, e1 := os.Pipe()
	rErr, wErr, e2 := os.Pipe()
	if e1 != nil || e2 != nil {
		t.Fatalf("pipe: %v %v", e1, e2)
	}
	os.Stdout, os.Stderr = wOut, wErr
	err = fn()
	os.Stdout, os.Stderr = origOut, origErr
	wOut.Close()
	wErr.Close()
	ob, _ := io.ReadAll(rOut)
	eb, _ := io.ReadAll(rErr)
	return string(ob), string(eb), err
}

const renderFlowFmt = `apiVersion: afon.dev/flow/v1
kind: Flow
metadata:
  name: t
spec:
  target:
    namespace: demo
  nodes:
    - id: app
      type: app-manifests
      config:
        name: hello
        image: %s
        port: 8080
        out: gen/app.yaml
`

// writeRenderFlow drops a flow file with the given image into a fresh
// temp dir and returns the flow path.
func writeRenderFlow(t *testing.T, image string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "flow.yaml")
	if err := os.WriteFile(path, []byte(strings.Replace(renderFlowFmt, "%s", image, 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestRender_FlagValidation(t *testing.T) {
	cases := []struct {
		name    string
		mutate  func()
		wantErr string
	}{
		{"node and all", func() { flagRenderNode, flagRenderAll = "app", true }, "--node and --all are mutually exclusive"},
		{"out without node", func() { flagRenderOut = "gen/x.yaml" }, "--out requires --node"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			resetRenderFlags(t, "nonexistent-flow.yaml")
			tc.mutate()
			_, _, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) })
			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("err = %v, want %q", err, tc.wantErr)
			}
		})
	}
}

// TestRender_WritesFileWithHeader: the happy path — a materialized
// app-manifests node renders to its out: path with the provenance
// header, statuses go to stderr, YAML goes to stdout, and a re-run is
// byte-identical (unchanged).
func TestRender_WritesFileWithHeader(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	resetRenderFlags(t, flow)

	stdout, stderr, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) })
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(filepath.Dir(flow), "gen", "app.yaml")
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(content), "# Generated by afon render") {
		t.Errorf("file missing provenance header:\n%.100s", content)
	}
	if !strings.Contains(string(content), "kind: Deployment") {
		t.Errorf("file missing Deployment:\n%s", content)
	}
	if !strings.Contains(stderr, "written") || !strings.Contains(stderr, "gen/app.yaml") {
		t.Errorf("stderr missing write status:\n%s", stderr)
	}
	if !strings.Contains(stdout, "# Generated by afon render") || !strings.Contains(stdout, "kind: Deployment") {
		t.Errorf("stdout missing rendered content:\n%s", stdout)
	}

	// Re-run: unchanged, file bytes untouched.
	before := string(content)
	stdout2, stderr2, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) })
	if err != nil {
		t.Fatal(err)
	}
	content2, _ := os.ReadFile(path)
	if string(content2) != before {
		t.Error("re-run rewrote the file")
	}
	if !strings.Contains(stderr2, "unchanged") {
		t.Errorf("second stderr missing unchanged:\n%s", stderr2)
	}
	if stdout2 != stdout {
		t.Error("second stdout differs from first")
	}
}

// TestRender_CheckAndStale: --check reports up-to-date on a fresh
// render, then stale after the flow's config changes — and modifies
// nothing.
func TestRender_CheckAndStale(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	resetRenderFlags(t, flow)
	if _, _, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) }); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(filepath.Dir(flow), "gen", "app.yaml")
	before, _ := os.ReadFile(path)

	flagRenderCheck = true
	_, stderr, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) })
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(stderr, "up-to-date") {
		t.Errorf("check stderr = %s, want up-to-date", stderr)
	}

	// Change the flow config: the file is now stale, not edited.
	stale := strings.ReplaceAll(string(mustRead(t, flow)), "nginx:1.27-alpine", "nginx:1.28")
	if err := os.WriteFile(flow, []byte(stale), 0o644); err != nil {
		t.Fatal(err)
	}
	_, stderr, err = captureStdoutStderr(t, func() error { return runRender(context.Background()) })
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(stderr, "stale") || !strings.Contains(stderr, "flow config changed since render") {
		t.Errorf("stale check stderr = %s", stderr)
	}
	after, _ := os.ReadFile(path)
	if string(after) != string(before) {
		t.Error("--check modified the file")
	}
}

// TestRender_RefusesHandEditThenForce: a hand-edited body blocks a
// plain render with an actionable error; --force takes ownership.
func TestRender_RefusesHandEditThenForce(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	resetRenderFlags(t, flow)
	if _, _, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) }); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(filepath.Dir(flow), "gen", "app.yaml")
	b, _ := os.ReadFile(path)
	handEdited := strings.Replace(string(b), "image: nginx:1.27-alpine", "image: nginx:evil", 1)
	if err := os.WriteFile(path, []byte(handEdited), 0o644); err != nil {
		t.Fatal(err)
	}

	_, _, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) })
	if err == nil || !strings.Contains(err.Error(), "edited") || !strings.Contains(err.Error(), "--force") {
		t.Fatalf("err = %v, want hand-edit refusal naming --force", err)
	}

	flagRenderForce = true
	if _, stderr, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) }); err != nil {
		t.Fatalf("force render: %v\nstderr: %s", err, stderr)
	}
	final, _ := os.ReadFile(path)
	if strings.Contains(string(final), "nginx:evil") {
		t.Error("force did not overwrite the hand-edit")
	}
}

// TestRender_NodeAndOutFlags: --node restricts the run and --out
// redirects the write away from the configured out: path.
func TestRender_NodeAndOutFlags(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	resetRenderFlags(t, flow)
	flagRenderNode = "app"
	flagRenderOut = filepath.Join(t.TempDir(), "adhoc.yaml")
	if _, stderr, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) }); err != nil {
		t.Fatalf("render --node: %v\nstderr: %s", err, stderr)
	}
	if _, err := os.Stat(flagRenderOut); err != nil {
		t.Errorf("--out file missing: %v", err)
	}
	if _, err := os.Stat(filepath.Join(filepath.Dir(flow), "gen", "app.yaml")); !os.IsNotExist(err) {
		t.Error("--out must not also write the configured out: path")
	}
}

// TestWarnStaleMaterialized: a fresh render warns about nothing; a
// flow edit after render surfaces the warning with node, path, and the
// command to fix it.
func TestWarnStaleMaterialized(t *testing.T) {
	flow := writeRenderFlow(t, "nginx:1.27-alpine")
	resetRenderFlags(t, flow)
	if _, _, err := captureStdoutStderr(t, func() error { return runRender(context.Background()) }); err != nil {
		t.Fatal(err)
	}
	cf, err := parseFlow(flow)
	if err != nil {
		t.Fatal(err)
	}
	stdout, stderr, err := captureStdoutStderr(t, func() error { return warnStaleMaterialized(cf) })
	if err != nil {
		t.Fatal(err)
	}
	if stdout != "" || stderr != "" {
		t.Errorf("fresh render warned: stdout=%q stderr=%q", stdout, stderr)
	}

	stale := strings.ReplaceAll(string(mustRead(t, flow)), "nginx:1.27-alpine", "nginx:1.28")
	if err := os.WriteFile(flow, []byte(stale), 0o644); err != nil {
		t.Fatal(err)
	}
	cf, err = parseFlow(flow)
	if err != nil {
		t.Fatal(err)
	}
	_, stderr, err = captureStdoutStderr(t, func() error { return warnStaleMaterialized(cf) })
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`warning: node "app"`, "stale", `afon render -f`} {
		if !strings.Contains(stderr, want) {
			t.Errorf("warning missing %q:\n%s", want, stderr)
		}
	}
}

// TestPrintActionOutputs: --show-rendered's printer dumps known
// outputs in sorted order to stderr (stdout stays clean for -o json).
func TestPrintActionOutputs(t *testing.T) {
	p := &engine.Plan{ActionOutputs: map[string]engine.Outputs{
		"seed": {"rendered": engine.KnownValue("seed-body\n")},
		"app":  {"rendered": engine.KnownValue("app-body\n")},
	}}
	_, stderr, err := captureStdoutStderr(t, func() error {
		printActionOutputs(p)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(stderr, "--- node app output rendered ---\napp-body") {
		t.Errorf("stderr missing app output:\n%s", stderr)
	}
	// Sorted: app before seed.
	if strings.Index(stderr, "node app") > strings.Index(stderr, "node seed") {
		t.Errorf("outputs not sorted:\n%s", stderr)
	}
}

func mustRead(t *testing.T, path string) []byte {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return b
}
