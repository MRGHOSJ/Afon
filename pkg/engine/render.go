// Provenance is the header afon render prepends to a materialized
// file: enough to detect hand-edits (BodyHash) and config drift
// (ConfigHash) later, plus the command that regenerates it. The header
// is # comments, so the file stays valid YAML.
type Provenance struct {
	Flow       string
	Node       string
	ConfigHash string
	BodyHash   string
	Rerender   string
}

// header renders the four-line provenance block, newline-terminated.
func (p Provenance) header() string {
	return fmt.Sprintf(
		"# Generated by afon render — do not edit unless you intend to take ownership.\n"+
			"# Flow: %s  node: %s\n"+
			"# Config hash: %s  Body hash: %s\n"+
			"# Re-render: %s\n",
		p.Flow, p.Node, p.ConfigHash, p.BodyHash, p.Rerender)
}

// parseProvenance splits a rendered file into its header and manifest
// body. ok is false when the content does not carry a valid header
// (foreign file, or a header line was deleted) — callers treat that as
// "edited" so a file render did not produce is never clobbered
// silently. The body is everything after the Re-render line, so body
// comments are never mistaken for header.
func parseProvenance(content []byte) (Provenance, []byte, bool) {
	if !bytes.HasPrefix(content, []byte("# Generated by afon render")) {
		return Provenance{}, nil, false
	}
	idx := bytes.Index(content, []byte("\n# Re-render:"))
	if idx < 0 {
		return Provenance{}, nil, false
	}
	nl := bytes.IndexByte(content[idx+1:], '\n')
	if nl < 0 {
		return Provenance{}, nil, false
	}
	headerEnd := idx + 1 + nl + 1
	header := string(content[:headerEnd])

	var meta Provenance
	for _, line := range strings.Split(header, "\n") {
		switch {
		case strings.HasPrefix(line, "# Flow: "):
			flow, node, ok := strings.Cut(strings.TrimPrefix(line, "# Flow: "), "  node: ")
			if !ok {
				return Provenance{}, nil, false
			}
			meta.Flow, meta.Node = flow, node
		case strings.HasPrefix(line, "# Config hash: "):
			fields := strings.Fields(line)
			if len(fields) < 7 {
				return Provenance{}, nil, false
			}
			meta.ConfigHash, meta.BodyHash = fields[3], fields[6]
		case strings.HasPrefix(line, "# Re-render: "):
			meta.Rerender = strings.TrimPrefix(line, "# Re-render: ")
		}
	}
	if meta.Flow == "" || meta.Node == "" || meta.ConfigHash == "" || meta.BodyHash == "" {
		return Provenance{}, nil, false
	}
	return meta, content[headerEnd:], true
}

// makeProvenance builds the header for a render. The body is
// normalized (guaranteed trailing newline) so the recorded BodyHash
// always matches what writeMaterialized writes.
func makeProvenance(flow, node, cfgHash, body string) (Provenance, string) {
	norm := normalizeBody(body)
	sum := sha256.Sum256([]byte(norm))
	return Provenance{
		Flow:       flow,
		Node:       node,
		ConfigHash: cfgHash,
		BodyHash:   hex.EncodeToString(sum[:]),
		Rerender:   "afon render -f " + flow,
	}, norm
}

// configHash hashes a node's marked (raw, unresolved) config. Marked,
// not resolved: the hash must be identical at render time and at plan
// time even when upstream outputs are uncached, and it must not churn
// when an upstream's cached bytes change without a flow edit. Markers
// serialize to their source form first — Normalize lives in pkg/driver
// and must not learn about engine types.
func configHash(cfg any) (string, error) {
	return hashPayload(markersToText(cfg))
}

// markersToText replaces Reference/Template markers with canonical
// strings (their ${node.output} source form) so a marked config
// round-trips through the hash as deterministic JSON.
func markersToText(v any) any {
	switch t := v.(type) {
	case Reference:
		if t.Reserved {
			return fmt.Sprintf("${%s.%s}", t.Output, t.Name)
		}
		return fmt.Sprintf("${%s.%s}", t.Node, t.Output)
	case Template:
		parts := make([]any, 0, len(t.Parts))
		for _, p := range t.Parts {
			parts = append(parts, markersToText(p))
		}
		return parts
	case map[string]any:
		out := make(map[string]any, len(t))
		for k, e := range t {
			out[k] = markersToText(e)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, e := range t {
			out[i] = markersToText(e)
		}
		return out
	default:
		return v
	}
}

func normalizeBody(body string) string {
	if !strings.HasSuffix(body, "\n") {
		return body + "\n"
	}
	return body
}

func hashHex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// writeMaterialized atomically writes header+body to path (creating
// parent directories), refusing to clobber a file whose body no longer
// matches its own header — a hand-edit — unless force. The write goes
// to a temp file in the same directory then renames, so a crash never
// leaves a half-written artifact.
func writeMaterialized(path, body string, meta Provenance, force bool) error {
	norm := normalizeBody(body)
	meta.BodyHash = hashHex([]byte(norm))

	fullPath := filepath.FromSlash(path)
	if b, err := os.ReadFile(fullPath); err == nil {
		existing, ebody, ok := parseProvenance(b)
		switch {
		case !ok:
			if !force {
				return fmt.Errorf("%s exists without a valid render header; refusing to overwrite without --force", path)
			}
		case hashHex(ebody) != existing.BodyHash:
			if !force {
				return fmt.Errorf("%s has been edited since it was rendered; refusing to clobber hand-edits — pass --force to overwrite", path)
			}
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("reading %s: %w", path, err)
	}

	dir := filepath.Dir(fullPath)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("creating directory for %s: %w", path, err)
	}
	tmp, err := os.CreateTemp(dir, ".afon-render-*")
	if err != nil {
		return fmt.Errorf("creating temp file for %s: %w", path, err)
	}
	tmpName := tmp.Name()
	if _, err := tmp.WriteString(meta.header() + norm); err != nil {
		tmp.Close()
		os.Remove(tmpName)
		return fmt.Errorf("writing %s: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpName)
		return fmt.Errorf("closing %s: %w", path, err)
	}
	if err := os.Chmod(tmpName, 0o644); err != nil {
		os.Remove(tmpName)
		return fmt.Errorf("setting permissions on %s: %w", path, err)
	}
	if err := os.Rename(tmpName, fullPath); err != nil {
		os.Remove(tmpName)
		return fmt.Errorf("committing %s: %w", path, err)
	}
	return nil
}

// StaleWarning reports one materialized node whose file was rendered
// from a different config than the flow now has — the user changed the
// flow and has not re-rendered. A warning, never an error: the file is
// still the artifact, and plan/apply use it as-is.
type StaleWarning struct {
	NodeID string
	Path   string
}

// StaleMaterialized compares each materialized node's current config
// hash against the provenance header of its file. Missing files and
// unparseable headers are skipped on purpose: a missing file is a hard
// error in plan/apply, and a tampered header is render's --force
// territory. Only the clean "rendered, then flow edited" case warns.
func StaleMaterialized(cf *CompiledFlow) ([]StaleWarning, error) {
	in := Inputs{FlowFile: cf.File, Target: cf.Target}
	var out []StaleWarning
	for _, id := range cf.Topo {
		cn := cf.byID[id]
		if cn.NT.Kind() != KindAction {
			continue
		}
		path, err := materializedPath(cn, in)
		if err != nil {
			return nil, fmt.Errorf("node %q: %w", cn.ID, err)
		}
		if path == "" {
			continue
		}
		b, err := os.ReadFile(filepath.FromSlash(path))
		if err != nil {
			continue
		}
		meta, _, ok := parseProvenance(b)
		if !ok {
			continue
		}
		cur, err := configHash(cn.Config)
		if err != nil {
			return nil, fmt.Errorf("node %q: %w", cn.ID, err)
		}
		if cur != meta.ConfigHash {
			out = append(out, StaleWarning{NodeID: cn.ID, Path: path})
		}
	}
	return out, nil
}

// RenderMode selects which action nodes render runs.
type RenderMode int

const (
	// RenderMaterialized runs the materialized nodes plus the action
	// ancestors they need for reference resolution — the default.
	RenderMaterialized RenderMode = iota
	// RenderAll runs every action node in the flow.
	RenderAll
)

// RenderOptions tunes one RenderActions call.
type RenderOptions struct {
	// Force overwrites hand-edited files.
	Force bool
	// Check compares instead of writing: files get up-to-date/edited/
	// stale/missing statuses and nothing is modified.
	Check bool
	// Only restricts the run to one node plus its action ancestors,
	// and restricts file writes and printed output to that node.
	Only string
	// Mode picks the target set when Only is empty.
	Mode RenderMode
	// Out (Only only) writes the node's output there instead of its
	// configured out: — ad-hoc rendering without touching the
	// artifact.
	Out string
}

// FileStatus is what render did (or would do) with one file.
type FileStatus string

const (
	FileWritten   FileStatus = "written"
	FileUnchanged FileStatus = "unchanged"
	FileUpToDate  FileStatus = "up-to-date"
	FileEdited    FileStatus = "edited"
	FileStale     FileStatus = "stale"
	FileMissing   FileStatus = "missing"
)

// FileOutcome is one materialized file's render result. Content is the
// would-be file (header + body) so callers can print exactly what is
// on disk without re-reading it.
type FileOutcome struct {
	NodeID  string
	Path    string
	Status  FileStatus
	Content string
	Diff    string
}

// RenderResult is what RenderActions ran and wrote.
type RenderResult struct {
	// Outputs maps every action node that ran to its Run outputs
	// (body only — headers exist only in files).
	Outputs map[string]Outputs
	// Files records one outcome per materialized file touched or
	// checked, in topological order.
	Files []FileOutcome
}

// RenderActions runs the action subgraph of cf in topological order
// and returns each action node's outputs. Resource nodes are skipped —
// render never touches a driver. Action nodes that materialize have
// their output written to their out: path with a provenance header,
// unless Check (compare only) or the edit check refuses without Force.
// Run is always called: render is the explicit build step, cache
// plays no part.
func RenderActions(ctx context.Context, cf *CompiledFlow, opts RenderOptions) (*RenderResult, error) {
	if opts.Out != "" && opts.Only == "" {
		return nil, fmt.Errorf("--out requires --node")
	}
	in := Inputs{FlowFile: cf.File, Target: cf.Target}
	targets, err := renderTargets(cf, in, opts)
	if err != nil {
		return nil, err
	}

	res := &RenderResult{Outputs: map[string]Outputs{}}
	for _, id := range cf.Topo {
		if !targets[id] {
			continue
		}
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		cn := cf.byID[id]
		resolved, err := Resolve(cn.Config, outputsLookup(res.Outputs))
		if err != nil {
			return nil, &ConfigError{Pos: cn.IDPos, Message: fmt.Sprintf("node %q: %v", cn.ID, err)}
		}
		if !resolved.Known {
			return nil, &ConfigError{Pos: cn.IDPos, Message: fmt.Sprintf(
				"node %q: upstream %q did not produce required outputs", cn.ID, resolved.UnknownFrom)}
		}
		nt, ok := cn.NT.(ActionType)
		if !ok {
			return nil, fmt.Errorf("node %q: render runs action nodes only (got kind %q)", cn.ID, cn.NT.Kind())
		}
		outs, err := nt.Run(ctx, resolved.Value, in)
		if err != nil {
			return nil, fmt.Errorf("node %q: %w", cn.ID, err)
		}
		res.Outputs[cn.ID] = outs

		if err := renderFile(cf, cn, outs, in, opts, res); err != nil {
			return nil, err
		}
	}
	return res, nil
}

// renderFile performs the file operation (write or check) for one
// rendered node, appending a FileOutcome when there is one.
func renderFile(cf *CompiledFlow, cn *CompiledNode, outs Outputs, in Inputs, opts RenderOptions, res *RenderResult) error {
	cfgPath, err := materializedPath(cn, in)
	if err != nil {
		return fmt.Errorf("node %q: %w", cn.ID, err)
	}
	opPath := ""
	switch {
	case opts.Out != "" && cn.ID == opts.Only:
		opPath = opts.Out
	case cfgPath != "" && (opts.Only == "" || cn.ID == opts.Only):
		opPath = cfgPath
	}
	if opPath == "" {
		return nil
	}

	declared := cn.NT.DeclaredOutputs()
	if len(declared) == 0 {
		return fmt.Errorf("node %q declares no outputs to write to %s", cn.ID, opPath)
	}
	raw, ok := outs[declared[0]]
	if !ok || !raw.Known {
		return fmt.Errorf("node %q: output %q is missing or unknown", cn.ID, declared[0])
	}
	body, ok := raw.Data.(string)
	if !ok {
		return fmt.Errorf("node %q: output %q must be a string to materialize, got %T", cn.ID, declared[0], raw.Data)
	}
	cfgH, err := configHash(cn.Config)
	if err != nil {
		return fmt.Errorf("node %q: %w", cn.ID, err)
	}
	meta, norm := makeProvenance(cf.File, cn.ID, cfgH, body)
	wouldBe := meta.header() + norm

	disk, readErr := os.ReadFile(filepath.FromSlash(opPath))
	exists := readErr == nil
	if readErr != nil && !os.IsNotExist(readErr) {
		return fmt.Errorf("reading %s: %w", opPath, readErr)
	}

	if opts.Check {
		res.Files = append(res.Files, checkFile(opPath, disk, exists, norm, cfgH, wouldBe))
		return nil
	}

	if exists {
		existing, ebody, ok := parseProvenance(disk)
		edited := !ok || hashHex(ebody) != existing.BodyHash
		if edited && !opts.Force {
			return fmt.Errorf(
				"refusing to overwrite edited file %s (its body no longer matches the render header); pass --force to take ownership",
				opPath)
		}
		if string(disk) == wouldBe {
			res.Files = append(res.Files, FileOutcome{
				NodeID: cn.ID, Path: opPath, Status: FileUnchanged, Content: wouldBe,
			})
			return nil
		}
	}
	if err := writeMaterialized(opPath, norm, meta, opts.Force); err != nil {
		return err
	}
	res.Files = append(res.Files, FileOutcome{
		NodeID: cn.ID, Path: opPath, Status: FileWritten, Content: wouldBe,
	})
	return nil
}

// checkFile classifies the on-disk state for --check without writing:
// missing, edited (body or header broken), stale (config changed since
// render), or up-to-date. Edited wins over stale — a hand-edit is the
// more urgent thing to report.
func checkFile(path string, disk []byte, exists bool, wantBody, cfgHash, wouldBe string) FileOutcome {
	out := FileOutcome{Path: path, Content: wouldBe}
	if !exists {
		out.Status = FileMissing
		out.Diff = "file does not exist"
		return out
	}
	existing, ebody, ok := parseProvenance(disk)
	if !ok {
		out.Status = FileEdited
		out.Diff = "no valid render header"
		return out
	}
	if hashHex(ebody) != existing.BodyHash {
		out.Status = FileEdited
		out.Diff = bodyDiff(string(ebody), wantBody)
		return out
	}
	if existing.ConfigHash != cfgHash {
		out.Status = FileStale
		out.Diff = "flow config changed since render"
		return out
	}
	out.Status = FileUpToDate
	return out
}

// bodyDiff reports the first differing line between the on-disk body
// and the body a re-render would produce — enough to see what changed
// without dumping both files.
func bodyDiff(got, want string) string {
	g := strings.Split(got, "\n")
	w := strings.Split(want, "\n")
	n := len(g)
	if len(w) < n {
		n = len(w)
	}
	for i := 0; i < n; i++ {
		if g[i] != w[i] {
			return fmt.Sprintf("first difference at line %d:\n  on disk:  %s\n  expected: %s", i+1, g[i], w[i])
		}
	}
	return fmt.Sprintf("length differs: on disk %d lines, expected %d", len(g), len(w))
}

// renderTargets decides which action nodes one render runs: Only plus
// its action ancestors, every action (RenderAll), or the
// materialized nodes plus their action ancestors (default).
func renderTargets(cf *CompiledFlow, in Inputs, opts RenderOptions) (map[string]bool, error) {
	isAction := func(cn *CompiledNode) bool { return cn.NT.Kind() == KindAction }

	if opts.Only != "" {
		cn, ok := cf.Node(opts.Only)
		if !ok {
			return nil, fmt.Errorf("node %q not found in flow", opts.Only)
		}
		if !isAction(cn) {
			return nil, fmt.Errorf("node %q is a %s; render runs action nodes only", opts.Only, cn.NT.Kind())
		}
		targets := actionAncestors(cf, opts.Only)
		targets[opts.Only] = true
		return targets, nil
	}

	if opts.Mode == RenderAll {
		targets := map[string]bool{}
		for _, cn := range cf.Nodes {
			if isAction(cn) {
				targets[cn.ID] = true
			}
		}
		return targets, nil
	}

	targets := map[string]bool{}
	materialized := 0
	for _, cn := range cf.Nodes {
		if !isAction(cn) {
			continue
		}
		path, err := materializedPath(cn, in)
		if err != nil {
			return nil, fmt.Errorf("node %q: %w", cn.ID, err)
		}
		if path == "" {
			continue
		}
		materialized++
		for id := range actionAncestors(cf, cn.ID) {
			targets[id] = true
		}
		targets[cn.ID] = true
	}
	if materialized == 0 {
		return nil, fmt.Errorf("no materialized nodes in flow; set out: on an action node, or use --node")
	}
	return targets, nil
}

// actionAncestors returns every action node upstream of id (refs and
// needs edges, resources filtered out after the walk so actions that
// feed a resource on the way are kept).
func actionAncestors(cf *CompiledFlow, id string) map[string]bool {
	rev := map[string][]string{}
	for _, cn := range cf.Nodes {
		for _, e := range cf.Graph.Edges(cn.ID) {
			rev[e[0]] = append(rev[e[0]], cn.ID)
		}
	}
	all := map[string]bool{}
	queue := []string{id}
	for len(queue) > 0 {
		cur := queue[0]
		queue = queue[1:]
		for _, up := range rev[cur] {
			if all[up] {
				continue
			}
			all[up] = true
			queue = append(queue, up)
		}
	}
	out := map[string]bool{}
	for nid := range all {
		if cn, ok := cf.Node(nid); ok && cn.NT.Kind() == KindAction {
			out[nid] = true
		}
	}
	return out
}
