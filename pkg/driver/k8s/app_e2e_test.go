// appE2EFlow is the materialized lifecycle a real user flow takes:
// app-manifests generates the YAML (out: generated.yaml), k8s-manifests
// reads that file back off disk, k8s-apply diffs it against the
// cluster. Namespace is test-ns so the driver's managed-namespace check
// passes; no target.context — this test never touches a kubeconfig.
const appE2EFlow = `apiVersion: afon.dev/flow/v1
kind: Flow
metadata:
  name: app-e2e
spec:
  target:
    namespace: ` + testNS + `
  nodes:
    - id: app
      type: app-manifests
      config:
        name: hello
        image: nginx:1.27-alpine
        port: 8080
        out: generated.yaml
    - id: manifests
      type: k8s-manifests
      config:
        paths:
          - generated.yaml
    - id: deploy
      type: k8s-apply
      config:
        manifests: ${manifests.rendered}
`

// compileAppE2E writes the flow to a temp dir and compiles it with the
// production node set (AppManifests + K8sManifests + K8sApply).
func compileAppE2E(t *testing.T) *engine.CompiledFlow {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "flow.yaml")
	if err := os.WriteFile(path, []byte(appE2EFlow), 0o644); err != nil {
		t.Fatal(err)
	}
	reg := engine.NewRegistry()
	for _, nt := range []engine.NodeType{engine.AppManifests{}, engine.K8sManifests{}, engine.K8sApply{}} {
		if err := reg.Register(nt); err != nil {
			t.Fatal(err)
		}
	}
	flow, err := schema.Parse(path)
	if err != nil {
		t.Fatal(err)
	}
	cf, err := engine.Compile(flow, reg)
	if err != nil {
		t.Fatal(err)
	}
	return cf
}

// TestAppManifests_EndToEnd runs the full materialized pipeline —
// render → plan → apply — through the real engine against the fake
// cluster, then re-plans to prove convergence. This is the contract
// examples/hello-app ships: a Deployment and Service land in the
// cluster from a 6-field app spec, and the rendered file is the only
// artifact plan ever reads.
func TestAppManifests_EndToEnd(t *testing.T) {
	ctx := context.Background()
	cf := compileAppE2E(t)
	store := engine.NewMemoryStore()

	// Render: writes generated.yaml next to the flow, headered.
	if _, err := engine.RenderActions(ctx, cf, engine.RenderOptions{}); err != nil {
		t.Fatalf("render: %v", err)
	}
	genPath := filepath.Join(filepath.Dir(cf.File), "generated.yaml")
	body, err := os.ReadFile(genPath)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"# Generated by afon render", "kind: Deployment", "kind: Service", "image: nginx:1.27-alpine", "targetPort: 8080"} {
		if !strings.Contains(string(body), want) {
			t.Errorf("generated.yaml missing %q:\n%s", want, body)
		}
	}

	// Plan against the fake cluster seeded with the managed namespace.
	// Look entries up by ID: app and manifests share no graph edge (the
	// file is a disk dependency, not a ref), so declaration order is the
	// only thing tying them together.
	d, dyn := newTestDriver(t, false, nil, seedNamespace())
	p, err := engine.BuildPlan(ctx, cf, store, d)
	if err != nil {
		t.Fatalf("plan: %v", err)
	}
	if e := entryByID(t, p, "app"); e.Status != engine.PlanFile || e.Reason == "" {
		t.Errorf("app entry = %+v, want file with path reason", e)
	}
	if e := entryByID(t, p, "manifests"); e.Status != engine.PlanWillRun {
		t.Errorf("manifests entry = %+v, want will-run", e)
	}
	if e := entryByID(t, p, "deploy"); e.Status != engine.PlanKnownAfterApply {
		t.Errorf("deploy entry = %+v, want known-after-apply", e)
	}

	// Apply: Deployment + Service must exist in the cluster afterwards.
	ares, err := engine.Apply(ctx, cf, store, d, engine.ExecutorOptions{})
	if err != nil {
		t.Fatalf("apply: %v", err)
	}
	for _, id := range []string{"app", "manifests", "deploy"} {
		r, ok := ares.Get(id)
		if !ok || r.Status != engine.StatusSucceeded {
			t.Errorf("node %s result = %+v, want succeeded", id, r)
		}
	}

	dep, err := dyn.Resource(deployGVR).Namespace(testNS).Get(ctx, "hello", metav1.GetOptions{})
	if err != nil {
		t.Fatalf("get Deployment: %v", err)
	}
	if got := digString(dep.Object, "spec", "template", "spec", "containers", 0, "image"); got != "nginx:1.27-alpine" {
		t.Errorf("deployment image = %q", got)
	}
	if got := digString(dep.Object, "metadata", "namespace"); got != testNS {
		t.Errorf("deployment namespace = %q", got)
	}
	if got := digString(dep.Object, "spec", "template", "spec", "containers", 0, "ports", 0, "containerPort"); got != "8080" {
		t.Errorf("containerPort = %q, want 8080", got)
	}
	if got := digString(dep.Object, "spec", "replicas"); got != "1" {
		t.Errorf("replicas = %q, want 1", got)
	}

	svc, err := dyn.Resource(svcGVR).Namespace(testNS).Get(ctx, "hello", metav1.GetOptions{})
	if err != nil {
		t.Fatalf("get Service: %v", err)
	}
	if got := digString(svc.Object, "spec", "ports", 0, "port"); got != "80" {
		t.Errorf("service port = %q, want 80", got)
	}
	if got := digString(svc.Object, "spec", "ports", 0, "targetPort"); got != "8080" {
		t.Errorf("targetPort = %q, want 8080", got)
	}

	// Re-plan: converged. The materialized node stays "file" (it never
	// caches), manifests is cached off the unchanged file, deploy is
	// none against live state.
	p, err = engine.BuildPlan(ctx, cf, store, d)
	if err != nil {
		t.Fatalf("re-plan: %v", err)
	}
	if e := entryByID(t, p, "app"); e.Status != engine.PlanFile {
		t.Errorf("warm app entry = %+v, want file", e)
	}
	if e := entryByID(t, p, "manifests"); e.Status != engine.PlanCached {
		t.Errorf("warm manifests entry = %+v, want cached", e)
	}
	if e := entryByID(t, p, "deploy"); e.Status != engine.PlanNone {
		t.Errorf("warm deploy entry = %+v, want none", e)
	}

	// Second apply: nothing changes, cluster state untouched.
	ares, err = engine.Apply(ctx, cf, store, d, engine.ExecutorOptions{})
	if err != nil {
		t.Fatalf("re-apply: %v", err)
	}
	if r, _ := ares.Get("deploy"); r.Cached || r.DiffCount != 0 {
		t.Errorf("warm deploy result = %+v, want cached/no-op", r)
	}
}

// entryByID returns one plan entry by node ID, failing the test when
// the node is absent.
func entryByID(t *testing.T, p *engine.Plan, id string) engine.PlanEntry {
	t.Helper()
	for _, e := range p.Entries {
		if e.NodeID == id {
			return e
		}
	}
	t.Fatalf("node %q missing from plan entries %+v", id, p.Entries)
	return engine.PlanEntry{}
}

// digString walks a nested unstructured structure, formatting the leaf
// as a string so int/int64/string all compare naturally.
func digString(m map[string]any, path ...any) string {
	var cur any = m
	for _, step := range path {
		switch s := step.(type) {
		case string:
			mm, ok := cur.(map[string]any)
			if !ok {
				return fmt.Sprintf("<not a mapping at %q: %T>", s, cur)
			}
			cur, ok = mm[s]
			if !ok {
				return "<missing>"
			}
		case int:
			list, ok := cur.([]any)
			if !ok || s >= len(list) {
				return "<missing>"
			}
			cur = list[s]
		}
	}
	return fmt.Sprintf("%v", cur)
}
